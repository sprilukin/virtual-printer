"""Scrubbing of canonical captures, with a mandatory exact-match leak check.

Three layers:
1. A denylist of attributes that are removed or replaced by stable fakes.
2. Substitution of the known real identifiers (hostname, IP, serial, MAC)
   inside every remaining string value.
3. A leak check over the whole result (names, nested values, decoded
   octet strings) that raises LeakError if any identifier survived.
Only layer 3 is the safety net; it does not trust the first two.
"""

from __future__ import annotations

import base64
import contextlib
import copy
import hashlib
import json
import re
import uuid
from dataclasses import dataclass, field

VIRTUAL_PREFIX = "[VIRTUAL] "
# Model-style names (printer-make-and-model, TXT ty/product) read better without brackets, but must still say "Virtual".
VIRTUAL_MODEL_PREFIX = "Virtual "

# Volatile or device-specific, regenerated by the server: dropped.
REMOVE_ATTRS = {
    "printer-current-time",
    "printer-up-time",
    "queued-job-count",
    "printer-state-change-time",
    "printer-state-change-date-time",
    "printer-config-change-time",
    "printer-config-change-date-time",
    "printer-alert",
    "printer-alert-description",
    "device-uri",
}
# Replaced wholesale by the stable fakes below.
NAME_ATTRS = {"printer-name", "printer-info", "printer-dns-sd-name"}
EMPTY_ATTRS = {"printer-location", "printer-organization", "printer-organizational-unit"}
TXT_BLANK = {"note"}


class LeakError(Exception):
    """A real identifier survived scrubbing."""


@dataclass
class Identifiers:
    hosts: list[str] = field(default_factory=list)
    ips: list[str] = field(default_factory=list)
    serials: list[str] = field(default_factory=list)
    macs: list[str] = field(default_factory=list)

    def variants(self) -> list[tuple[str, str]]:
        """(kind, text) pairs: every spelling of every identifier."""
        out: list[tuple[str, str]] = []
        for h in self.hosts:
            h = h.strip().rstrip(".")
            out.append(("host", h))
            if h.lower().endswith(".local"):
                out.append(("host", h[: -len(".local")]))
        out += [("ip", i.strip()) for i in self.ips]
        out += [("serial", s.strip()) for s in self.serials]
        for m in self.macs:
            hexs = re.sub(r"[^0-9a-fA-F]", "", m)
            if len(hexs) != 12:
                raise ValueError(f"not a MAC address: {m!r}")
            pairs = [hexs[i : i + 2] for i in range(0, 12, 2)]
            quads = [hexs[i : i + 4] for i in range(0, 12, 4)]
            for text in (":".join(pairs), "-".join(pairs), ".".join(quads), hexs):
                out.append(("mac", text))
        seen, uniq = set(), []
        for kind, text in out:
            if len(text) < 4:
                raise ValueError(f"identifier too short to match safely: {text!r}")
            if text.lower() not in seen:
                seen.add(text.lower())
                uniq.append((kind, text))
        return sorted(uniq, key=lambda kt: -len(kt[1]))


@dataclass
class Fakes:
    """Deterministic fakes derived from the profile name, never from real data."""

    name: str

    def _h(self, label: str) -> bytes:
        return hashlib.sha256(f"virtual-printer/{self.name}/{label}".encode()).digest()

    @property
    def host(self) -> str:
        return f"vp-{self.name}"

    @property
    def uuid(self) -> str:
        return str(uuid.UUID(bytes=self._h("uuid")[:16], version=5))

    @property
    def mac_hex(self) -> str:
        b = bytearray(self._h("mac")[:6])
        b[0] = (b[0] & 0xFC) | 0x02  # locally administered, unicast
        return bytes(b).hex()

    @property
    def ip(self) -> str:
        return f"192.0.2.{self._h('ip')[0] % 250 + 2}"  # TEST-NET-1

    @property
    def serial(self) -> str:
        return "VP" + self._h("serial")[:5].hex().upper()


def _fake_mac_like(match: str, fake_hex: str) -> str:
    sep = next((c for c in ":-." if c in match), "")
    if sep == ".":
        text = ".".join(fake_hex[i : i + 4] for i in range(0, 12, 4))
    elif sep:
        text = sep.join(fake_hex[i : i + 2] for i in range(0, 12, 2))
    else:
        text = fake_hex
    return text.upper() if match.upper() == match and re.search("[A-F]", match.upper()) else text


class _Substituter:
    def __init__(self, ids: Identifiers, fakes: Fakes):
        self.fakes = fakes
        self.kind_of = {t.lower(): k for k, t in ids.variants()}
        texts = [t for _, t in ids.variants()]
        self.rx = re.compile("|".join(re.escape(t) for t in texts), re.I) if texts else None
        self.count = 0

    def _repl(self, m: re.Match) -> str:
        self.count += 1
        text = m.group(0)
        kind = self.kind_of[text.lower()]
        if kind == "host":
            return self.fakes.host + (".local" if text.lower().endswith(".local") else "")
        if kind == "ip":
            return self.fakes.ip
        if kind == "serial":
            return self.fakes.serial
        return _fake_mac_like(text, self.fakes.mac_hex)

    def string(self, s: str) -> str:
        return self.rx.sub(self._repl, s) if self.rx else s

    def value(self, v):
        if isinstance(v, str):
            return self.string(v)
        if isinstance(v, dict):
            if "members" in v:
                return {"members": [self.attr(m) for m in v["members"]]}
            if "lang" in v and "value" in v:
                return {"lang": v["lang"], "value": self.string(v["value"])}
        return v

    def attr(self, a: dict) -> dict:
        return {**a, "values": [self.value(v) for v in a["values"]]}


def _model_of(canonical: dict) -> str:
    for a in canonical["attributes"]:
        if a["name"] == "printer-make-and-model" and a["values"]:
            v = a["values"][0]
            return v["value"] if isinstance(v, dict) else v
    return "Printer"


def _text_like(tag: str, text: str):
    return {"lang": "en", "value": text} if tag.endswith("WithLanguage") else text


def scrub(canonical: dict, name: str, ids: Identifiers) -> dict:
    """Return the scrubbed profile document. Raises LeakError on any survivor."""
    fakes = Fakes(name)
    model = _model_of(canonical)
    virtual_name = VIRTUAL_PREFIX + model
    sub = _Substituter(ids, fakes)

    attrs = []
    for a in copy.deepcopy(canonical["attributes"]):
        n = a["name"]
        if n in REMOVE_ATTRS:
            continue
        if n in NAME_ATTRS:
            a["values"] = [_text_like(a["tag"], virtual_name)]
        elif n == "printer-make-and-model":
            a["values"] = [_text_like(a["tag"], VIRTUAL_MODEL_PREFIX + model)]
        elif n in EMPTY_ATTRS:
            a["values"] = [_text_like(a["tag"], "") for _ in a["values"]]
        elif n == "printer-uuid":
            a["values"] = [f"urn:uuid:{fakes.uuid}"]
        elif n == "printer-geo-location":
            a["tag"], a["values"] = "unknown", []
        else:
            a = sub.attr(a)
        attrs.append(a)

    dns = None
    if canonical.get("dnssd"):
        d = canonical["dnssd"]
        txt = []
        for k, v in d["txt"]:
            if k.upper() == "UUID":
                v = fakes.uuid
            elif k in TXT_BLANK:
                v = ""
            elif k == "ty":
                v = VIRTUAL_MODEL_PREFIX + model
            elif k == "product":
                v = f"({VIRTUAL_MODEL_PREFIX}{model})"
            else:
                v = sub.string(v)
            txt.append([k, v])
        dns = {
            "service_type": d.get("service_type", "_ipp._tcp"),
            "service_name": virtual_name,
            "txt": txt,
        }

    profile = {
        "format": 1,
        "name": name,
        "description": f"Scrubbed capture of {model}",
        "ipp_version": canonical.get("ipp_version", "2.0"),
        "attributes": attrs,
        "dnssd": dns,
        "options": {"validation": "strict"},
    }
    check_leaks(profile, ids)
    return profile


