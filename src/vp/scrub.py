def _walk(node, path: str):
    """Yield (path, text) for every string reachable, plus decoded blobs."""
    if isinstance(node, str):
        yield path, node
    elif isinstance(node, dict):
        for k, v in node.items():
            yield f"{path}.{k}(key)", str(k)
            if k == "base64" and isinstance(v, str):
                with contextlib.suppress(ValueError):
                    yield f"{path}.base64(decoded)", base64.b64decode(v).decode("latin-1")
            elif k == "hex" and isinstance(v, str):
                with contextlib.suppress(ValueError):
                    yield f"{path}.hex(decoded)", bytes.fromhex(v).decode("latin-1")
            yield from _walk(v, f"{path}.{k}")
    elif isinstance(node, list):
        for i, v in enumerate(node):
            yield from _walk(v, f"{path}[{i}]")


def check_leaks(doc: dict, ids: Identifiers) -> None:
    """Fail if any identifier appears anywhere in `doc` (exact match, any case)."""
    variants = ids.variants()
    hits = []
    texts = list(_walk(doc, "$"))
    texts.append(("$(serialised)", json.dumps(doc, ensure_ascii=False)))
    for path, text in texts:
        low = text.lower()
        for kind, ident in variants:
            if ident.lower() in low:
                hits.append(f"{kind} at {path}")
    if hits:
        # Report kind and location only: never echo the identifier.
        unique = sorted(set(hits))
        raise LeakError(
            f"{len(unique)} leak(s) after scrubbing: "
            + "; ".join(unique[:10])
            + ". Extend the denylist in vp/scrub.py and rerun."
        )
